import assert from 'node:assert/strict';
import { parseRows, age, resumeArgv } from './logic.mjs';
assert.deepEqual(resumeArgv('hermes', 'local-123'), ['hermes', '--resume', 'local-123']);
assert.deepEqual(resumeArgv('pig', 'abcd'), ['pig', '--session', 'abcd']);
assert.deepEqual(resumeArgv('claude', 'abcd-123'), ['claude', '--resume', 'abcd-123']);
assert.deepEqual(resumeArgv('codex', 'abcd-123'), ['codex', 'resume', 'abcd-123']);
assert.deepEqual(resumeArgv('opencode', 'abcd-123'), ['opencode', '--session', 'abcd-123']);
assert.equal(resumeArgv('codex', 'bad;cmd'), null);
assert.equal(resumeArgv('codex', '--delete'), null);
assert.equal(resumeArgv('pi', 'bad;cmd'), null);
assert.equal(age(100, 100 + 2 * 86400), '2d');
assert.deepEqual(parseRows('[{"app":"pi","id":"abcd","timestamp":1},{"app":"hermes","id":"efgh","timestamp":3}]').map(x => x.id), ['efgh','abcd']);
assert.deepEqual(parseRows('[{"app":"claude","id":"claude-1","timestamp":1},{"app":"codex","id":"codex-1","timestamp":2},{"app":"opencode","id":"open-1","timestamp":3},{"app":"codex","id":"--delete","timestamp":4}]').map(x => x.id), ['open-1','codex-1','claude-1']);
assert.deepEqual(parseRows('not json'), []);
console.log('sessions logic ok');
